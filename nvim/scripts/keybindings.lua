-- Generates KEYBINDINGS.md from the keymaps Neovim actually has loaded.
-- Run from ~/.config/nvim:
--   nvim --headless -c 'luafile scripts/keybindings.lua'

local out_path = vim.fn.stdpath("config") .. "/KEYBINDINGS.md"

-- LazyVim installs most keymaps on VeryLazy, which headless Neovim never fires.
vim.api.nvim_exec_autocmds("User", { pattern = "VeryLazy" })
vim.wait(1000)

-- Splits a readable lhs ("<leader>" already expanded to " ") into key tokens.
local function tokens(lhs)
  local parts, i = {}, 1
  while i <= #lhs do
    local tok = lhs:match("^<[^<>]+>", i) or lhs:sub(i, i)
    parts[#parts + 1] = (tok == " " or tok == "<Space>") and "Space" or tok
    i = i + #tok
  end
  return parts
end

local function pretty(lhs)
  return table.concat(tokens(lhs), " ")
end

local function escape(s)
  return (s:gsub("|", "\\|"))
end

local function useful(map)
  return map.desc and map.desc ~= "" and not map.lhs:find("<Plug>") and not map.lhs:find("<SNR>")
end

-- which-key group names keyed by the key after leader, e.g. "c" -> "code".
local groups = {}
local function add_group(lhs, name)
  local t = tokens(lhs)
  if #t == 2 and t[1] == "Space" then
    groups[t[2]:lower()] = groups[t[2]:lower()] or name
  end
end
for _, spec in ipairs(LazyVim.opts("which-key.nvim").spec or {}) do
  for _, item in ipairs(spec) do
    if type(item) == "table" and type(item.group) == "string" and type(item[1]) == "string" then
      add_group(item[1]:gsub("<leader>", " "), item.group)
    end
  end
end
-- Some extras declare their group as a keymap with a "+name" description instead.
for _, map in ipairs(vim.api.nvim_get_keymap("n")) do
  if map.desc and map.desc:match("^%+") then
    add_group(map.lhs, map.desc:sub(2))
  end
end

local leader = vim.g.mapleader
local function group_of(lhs)
  return groups[(tokens(lhs)[2] or ""):lower()] or "other"
end

-- Global leader keymaps, normal mode.
local by_group = {}
for _, map in ipairs(vim.api.nvim_get_keymap("n")) do
  if useful(map) and map.lhs:sub(1, #leader) == leader and #map.lhs > #leader and not map.desc:match("^%+") then
    local g = #tokens(map.lhs) == 2 and "top level" or group_of(map.lhs)
    by_group[g] = by_group[g] or {}
    table.insert(by_group[g], map)
  end
end

-- Buffer-local keymaps in a Rust file, from rust-analyzer + rustaceanvim.
local dir = vim.fn.tempname()
vim.fn.mkdir(dir .. "/src", "p")
vim.fn.writefile({ "[package]", 'name = "probe"', 'version = "0.1.0"', 'edition = "2021"' }, dir .. "/Cargo.toml")
vim.fn.writefile({ "fn main() {}" }, dir .. "/src/main.rs")
vim.cmd.edit(dir .. "/src/main.rs")
local attached = vim.wait(30000, function()
  return #vim.lsp.get_clients({ bufnr = 0, name = "rust-analyzer" }) > 0
end, 200)
vim.wait(1000)
local global_desc = {}
for _, map in ipairs(vim.api.nvim_get_keymap("n")) do
  global_desc[map.lhs] = map.desc
end
local rust_maps = {}
if attached then
  for _, map in ipairs(vim.api.nvim_buf_get_keymap(0, "n")) do
    if useful(map) then
      local shadowed = global_desc[map.lhs]
      if shadowed and shadowed ~= map.desc then
        map = { lhs = map.lhs, desc = ("%s _(replaces global: %s)_"):format(map.desc, shadowed) }
      end
      table.insert(rust_maps, map)
    end
  end
end

-- neo-tree's keys inside the tree window.
local tree_maps = {}
local ok, nt_defaults = pcall(require, "neo-tree.defaults")
if ok then
  local mappings = vim.tbl_extend(
    "force",
    nt_defaults.window.mappings or {},
    (LazyVim.opts("neo-tree.nvim").window or {}).mappings or {}
  )
  for lhs, action in pairs(mappings) do
    local name = type(action) == "string" and action
      or (type(action) == "table" and (action.desc or action[1]))
      or nil
    if type(name) == "string" and name ~= "none" then
      table.insert(tree_maps, { lhs = lhs, desc = (name:gsub("_", " ")) })
    end
  end
end

local lines = {
  "# Keybindings",
  "",
  "Generated by `scripts/keybindings.lua` on " .. os.date("%Y-%m-%d") .. ". Do not edit by hand; rerun:",
  "",
  "```sh",
  "cd ~/.config/nvim && nvim --headless -c 'luafile scripts/keybindings.lua'",
  "```",
  "",
  "Leader is **Space**. In Neovim, press `Space` and wait for which-key, or `Space s k` to search all keymaps.",
  "",
}

local function table_of(maps)
  table.sort(maps, function(a, b)
    return a.lhs < b.lhs
  end)
  lines[#lines + 1] = "| Keys | Action |"
  lines[#lines + 1] = "|---|---|"
  local seen = {}
  for _, map in ipairs(maps) do
    if not seen[map.lhs] then
      seen[map.lhs] = true
      local keys = escape(pretty(map.lhs))
      local code = keys:find("`") and ("`` " .. keys .. " ``") or ("`" .. keys .. "`")
      lines[#lines + 1] = ("| %s | %s |"):format(code, escape(map.desc))
    end
  end
  lines[#lines + 1] = ""
end

lines[#lines + 1] = "## Rust files"
lines[#lines + 1] = ""
if attached then
  lines[#lines + 1] = "Only active in `.rs` buffers once rust-analyzer attaches."
  lines[#lines + 1] = ""
  table_of(rust_maps)
else
  lines[#lines + 1] = "_rust-analyzer did not attach while generating; is it on PATH?_"
  lines[#lines + 1] = ""
end

lines[#lines + 1] = "## File tree (inside neo-tree)"
lines[#lines + 1] = ""
table_of(tree_maps)

-- Rust-workflow groups first, then everything else alphabetically.
local order = { "code", "debug", "profiler", "test", "file/find", "search", "diagnostics/quickfix", "git", "hunks" }
local placed = {}
for _, g in ipairs(order) do
  placed[g] = true
end
local rest = {}
for g in pairs(by_group) do
  if not placed[g] then
    rest[#rest + 1] = g
  end
end
table.sort(rest)
vim.list_extend(order, rest)

for _, g in ipairs(order) do
  if by_group[g] then
    lines[#lines + 1] = "## Leader: " .. g
    lines[#lines + 1] = ""
    table_of(by_group[g])
  end
end

vim.fn.writefile(lines, out_path)
vim.fn.delete(dir, "rf")
print("wrote " .. out_path)
vim.cmd("qa!")
